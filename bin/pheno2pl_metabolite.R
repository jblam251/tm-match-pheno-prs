## convert per-cohort metabolon peak area datasets to regenie format
## jake blamer - 03.09.2026
##
## DESCRIPTION
## this script 
##
## USAGE
## Rscript metabolon2regenie.R --peak_areas [peaks.txt] --annotation [metabolite.annotation.txt] --traits [traits.txt] --out [out.regenie.txt]



#parse arguments from command line
library(optparse)
options=list(
  make_option(c("-p", "--peak_areas"), action = "store", default = NA, type = "character", help="metabolite peak areas file generated by metabolon, often called [Study].BatchNormData.all.txt"),
  make_option(c("-a", "--annotation"), action = "store", default = NA, type = "character", help="metabolite annotation file generated by metabolon, often called [Study].ChemicalAnnotation.all.txt"),
  make_option(c("-t", "--traits"), action = "store", default = NA, type = "character", help="single-column file of trait/metabolite names used for PRS generation"),
  make_option(c("-i", "--imputation"), action = "store", default = F, type = "logical", help="logical to determine whether half-minimum imputation should be performed (default=F)"),
  make_option(c("-o", "--out"), action = "store", default = NA, type = "character", help="output file name")
)
args=parse_args(OptionParser(option_list = options))


# read in pgs traits
traits=as.character(read.table(args$traits, header=F, sep="\n")[,1])

# read in metabolon peak areas
pa=read.csv(args$peak_areas, header=T, sep="\t")
pa=as.data.frame(pa)

# read in metabolon metabolite annotation file
chemanno=read.csv(args$annotation, header=T, sep="\t")

#fix the metabolites with duplicated HMDBs (Bing resolved this by adding a suffex of ".2")
chemanno$HMDB[which(duplicated(chemanno$HMDB))]=paste0(chemanno$HMDB[which(duplicated(chemanno$HMDB))], ".2")
chemanno$HMDB[which(chemanno$HMDB==".2")]=""
#fix the metabolites that have multiple HMDBs seperated by a comma
chemanno$HMDB=gsub(",", ".", chemanno$HMDB)
#fix the metabolites that are assigned to multiple HMDBs
chemanno.split.hmdb=data.frame(
  chemanno[rep(seq_len(nrow(chemanno)), lengths(strsplit(chemanno$HMDB, ","))), ],
  HMDB.fix = unlist(strsplit(chemanno$HMDB, ","))
)
chemanno.split.hmdb$HMDB=chemanno.split.hmdb$HMDB.fix
chemanno.split.hmdb$HMDB.fix=NULL
chemanno=rbind(chemanno.split.hmdb, chemanno[which(chemanno$HMDB==""),])
rm(chemanno.split.hmdb)


# column HMDB should now match traits in PRS, now run the overlap
chemanno$chem.match=chemanno$HMDB
chemanno$chem.match[which(chemanno$chem.match%in%setdiff(chemanno$chem.match, traits))]=NA
chemanno$chem.match[which(is.na(chemanno$chem.match))]=paste0("HMDB.", tolower(gsub("[^[:alnum:]]", "", chemanno$CHEMICAL_NAME[which(is.na(chemanno$chem.match))])))
chemanno$chem.match[which(chemanno$chem.match%in%setdiff(chemanno$chem.match, traits))]=NA


# rename assay column names in peak area file to match prs
colnames(pa)=chemanno$chem.match[match(colnames(pa), paste0("X",chemanno$CHEM_ID))]
colnames(pa)[1]="SAMPLE_ID"
if(any(is.na(colnames(pa)))) {pa=pa[,-which(is.na(colnames(pa)))]}

# create FID and IID columns
pa$FID=pa$SAMPLE_ID
pa$IID=pa$SAMPLE_ID
pa$SAMPLE_ID=NULL
pa=pa[,c((ncol(pa)-1), ncol(pa), 1:(ncol(pa)-2))]

# any metabolites that are missing >50% of samples?
fail.traits=names(which(colSums(apply(pa[,-(1:2)], 2, is.na))/(nrow(pa)-2)>0.50))
if(length(fail.traits)!=0) { pa=pa[,-which(colnames(pa)%in%fail.traits),] }

# any duplicate samples in phenotypes?
dup.samples=c()
if(any(duplicated(pa[,1]))) {
	dup.samples=pa[,1][which(duplicated(pa[,1]))]
	pa=pa[-which(pa[,1]%in%dup.samples),]
}

# print some stats
writeLines(paste0("traits detected in PRS trait file : ", length(traits)))
writeLines(paste0("traits matched in peak areas : ", length(intersect(traits, chemanno$chem.match))))
writeLines(paste0("traits removed due to missingness >50% samples : ", length(fail.traits)))
writeLines(paste0("resulting number of missing data points in peak area file : ", length(which(is.na(pa))), " (", round(100*((length(which(is.na(pa))))/(nrow(pa)*(ncol(pa)-2))),2), "%)"))
writeLines(paste0("duplicate samples identified and removed : ", length(dup.samples)))
writeLines(paste0(dup.samples, collapse=","))




# write reforamtted pa data in regenie format
write.table(pa, paste0(args$out, ".wide.tsv"), sep="\t", col.names=T, row.names=F, quote=F)
writeLines(paste0("reforamtted peak area data written to : ", args$out))
